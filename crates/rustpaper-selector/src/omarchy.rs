// Desktop integration with Omarchy (Hyprland): the selector follows the
// active Omarchy theme's colors, and switches with it.
//
// Omarchy publishes the current theme in
// $XDG_STATE_HOME/omarchy/current/theme/colors.toml: a flat semantic palette
// (`background`, `foreground`, `accent`, `red`, ...) plus `mode` (dark /
// light). `current/theme.generation` changes on every theme switch, so a
// cheap poll of that one file is enough to notice it.

use std::collections::BTreeMap;
use std::path::PathBuf;
use std::time::Duration;

use serde::Serialize;
use tauri::Emitter;

/// How often the theme generation file is checked.
const POLL: Duration = Duration::from_secs(2);

#[derive(Serialize, Clone, Debug, PartialEq)]
pub struct Theme {
    pub name: String,
    /// "dark" | "light"
    pub mode: String,
    /// semantic name -> "#rrggbb" (only hex colors are kept)
    pub colors: BTreeMap<String, String>,
}

fn current_dir() -> Option<PathBuf> {
    let state = std::env::var_os("XDG_STATE_HOME")
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("HOME").map(|h| PathBuf::from(h).join(".local/state")))?;
    Some(state.join("omarchy").join("current"))
}

/// The active Omarchy theme, None outside Omarchy.
pub fn theme() -> Option<Theme> {
    let dir = current_dir()?;
    let text = std::fs::read_to_string(dir.join("theme").join("colors.toml")).ok()?;
    let name = std::fs::read_to_string(dir.join("theme.name"))
        .map(|n| n.trim().to_string())
        .unwrap_or_default();
    parse_colors(&text, name)
}

/// `key = "value"` lines of colors.toml (Omarchy writes nothing else: no
/// tables, no arrays). Values must be hex colors, except `mode`; the result
/// ends up in CSS custom properties, so anything else is dropped.
fn parse_colors(text: &str, name: String) -> Option<Theme> {
    let mut colors = BTreeMap::new();
    let mut mode = String::from("dark");
    for line in text.lines() {
        let line = line.trim();
        if line.starts_with('#') || line.is_empty() {
            continue;
        }
        let Some((key, value)) = line.split_once('=') else {
            continue;
        };
        let key = key.trim();
        let value = value.trim().trim_matches('"');
        if key == "mode" {
            if value == "light" || value == "dark" {
                mode = value.to_string();
            }
        } else if is_key(key) && is_hex_color(value) {
            colors.insert(key.to_string(), value.to_ascii_lowercase());
        }
    }
    // a palette without the basics is not a theme we can apply
    (colors.contains_key("background") && colors.contains_key("foreground")).then_some(Theme {
        name,
        mode,
        colors,
    })
}

fn is_key(k: &str) -> bool {
    !k.is_empty()
        && k.bytes()
            .all(|b| b.is_ascii_lowercase() || b == b'_' || b.is_ascii_digit())
}

fn is_hex_color(v: &str) -> bool {
    let Some(hex) = v.strip_prefix('#') else {
        return false;
    };
    matches!(hex.len(), 3 | 6 | 8) && hex.bytes().all(|b| b.is_ascii_hexdigit())
}

/// Emits `theme-changed` (the new Theme, or null) whenever Omarchy switches
/// themes. A no-op loop outside Omarchy costs one failed stat every POLL.
pub fn watch(app: tauri::AppHandle) {
    std::thread::spawn(move || {
        let generation =
            || current_dir().and_then(|d| std::fs::read_to_string(d.join("theme.generation")).ok());
        let mut last = generation();
        loop {
            std::thread::sleep(POLL);
            let now = generation();
            if now != last {
                last = now;
                let _ = app.emit("theme-changed", theme());
            }
        }
    });
}

// ---- a theme from the wallpaper (like Aether) -----------------------------

/// The Omarchy theme Rustpaper writes: one folder, rewritten for every
/// wallpaper (like Aether's `aether` theme), so the theme list stays clean.
pub const WALLPAPER_THEME: &str = "rustpaper";
/// First line of the colors.toml Rustpaper writes; a folder without it is
/// someone else's theme and is never overwritten.
const MARKER: &str = "# Generated by Rustpaper";

fn config_home() -> Option<PathBuf> {
    std::env::var_os("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("HOME").map(|h| PathBuf::from(h).join(".config")))
}

fn on_path(cmd: &str) -> Option<PathBuf> {
    std::env::split_paths(&std::env::var_os("PATH")?)
        .map(|d| d.join(cmd))
        .find(|p| p.is_file())
}

/// Omarchy is installed: its themes folder and `omarchy-theme-set`.
pub fn available() -> bool {
    config_home().is_some_and(|c| c.join("omarchy").is_dir())
        && on_path("omarchy-theme-set").is_some()
}

/// The palette of an image (a wallpaper's preview): decoded, downscaled to
/// at most 160 px (plenty for dominant colors), then palette.rs.
pub fn image_palette(image: &std::path::Path) -> Result<crate::palette::Palette, String> {
    let img = image::open(image).map_err(|e| format!("{}: {e}", image.display()))?;
    let small = img.thumbnail(160, 160).to_rgb8();
    let pixels: Vec<[u8; 3]> = small.pixels().map(|p| p.0).collect();
    Ok(crate::palette::palette_from_pixels(&pixels))
}

/// The `k` dominant colors of an image, most common first, as `#rrggbb`
/// (color suggestions in the customization panel). Near-duplicates are
/// merged so the suggestions differ visibly.
pub fn image_colors(image: &std::path::Path, k: usize) -> Result<Vec<String>, String> {
    let img = image::open(image).map_err(|e| format!("{}: {e}", image.display()))?;
    let small = img.thumbnail(160, 160).to_rgb8();
    let pixels: Vec<[u8; 3]> = small.pixels().map(|p| p.0).collect();
    let mut out: Vec<String> = Vec::new();
    for s in crate::palette::dominant_colors(&pixels, k * 3) {
        let hex = s.color.hex();
        // (70 of 765: below that, two greens of one image looked the same)
        let close = out.iter().any(|h| hex_distance(h, &hex) < 70);
        if !close {
            out.push(hex);
        }
        if out.len() == k {
            break;
        }
    }
    Ok(out)
}

/// Manhattan distance between two `#rrggbb` colors (0..765).
fn hex_distance(a: &str, b: &str) -> u32 {
    let ch = |h: &str, i: usize| {
        u8::from_str_radix(h.get(i..i + 2).unwrap_or("00"), 16).unwrap_or(0) as i32
    };
    (1..7).step_by(2).map(|i| ch(a, i).abs_diff(ch(b, i))).sum()
}

/// Writes ~/.config/omarchy/themes/rustpaper from a wallpaper's preview and
/// applies it with `omarchy-theme-set` (which also generates every app's
/// colors from colors.toml and sets the desktop background to the preview,
/// shown under the live wallpaper). Blocking: the switch takes seconds.
pub fn apply_wallpaper_theme(
    id: &str,
    title: &str,
    preview: &std::path::Path,
) -> Result<(), String> {
    if !available() {
        return Err("Omarchy is not installed (no omarchy-theme-set)".into());
    }
    let palette = image_palette(preview)?;
    let dir = config_home()
        .ok_or("no config directory")?
        .join("omarchy/themes")
        .join(WALLPAPER_THEME);
    let colors = dir.join("colors.toml");
    if let Ok(existing) = std::fs::read_to_string(&colors)
        && !existing.starts_with(MARKER)
    {
        return Err(format!(
            "{} is not a Rustpaper theme; not overwriting it",
            dir.display()
        ));
    }
    let backgrounds = dir.join("backgrounds");
    let _ = std::fs::remove_dir_all(&backgrounds);
    std::fs::create_dir_all(&backgrounds).map_err(|e| format!("{}: {e}", backgrounds.display()))?;
    let source = if title.is_empty() {
        id.to_string()
    } else {
        format!("{title} ({id})")
    };
    // keep the marker the first line, the source on one line
    let source = source.replace(['\n', '\r'], " ");
    std::fs::write(&colors, palette.to_colors_toml(&source)).map_err(|e| e.to_string())?;
    std::fs::write(dir.join("icons.theme"), palette.icon_theme()).map_err(|e| e.to_string())?;
    // background + theme picker preview: the wallpaper's preview, as PNG when
    // it is a GIF (video wallpapers; Omarchy's background wants a still)
    let ext = preview
        .extension()
        .and_then(|e| e.to_str())
        .map(str::to_ascii_lowercase)
        .unwrap_or_default();
    let is_gif = ext == "gif";
    let still = |dest: &std::path::Path| -> Result<(), String> {
        if is_gif {
            image::open(preview)
                .and_then(|i| i.save(dest.with_extension("png")))
                .map_err(|e| e.to_string())
        } else {
            std::fs::copy(preview, dest)
                .map(|_| ())
                .map_err(|e| e.to_string())
        }
    };
    let ext = if is_gif { "png".to_string() } else { ext };
    for old in ["preview.png", "preview.jpg", "preview.jpeg", "preview.webp"] {
        let _ = std::fs::remove_file(dir.join(old));
    }
    still(&backgrounds.join(format!("rustpaper-{id}.{ext}")))?;
    still(&dir.join(format!("preview.{ext}")))?;

    let out = std::process::Command::new("omarchy-theme-set")
        .arg(WALLPAPER_THEME)
        // no terminal: nothing in the switch may prompt
        .stdin(std::process::Stdio::null())
        .output()
        .map_err(|e| format!("omarchy-theme-set: {e}"))?;
    if !out.status.success() {
        // it reports some errors on stdout ("Theme '...' does not exist")
        let text = [&out.stderr, &out.stdout].map(|b| String::from_utf8_lossy(b).into_owned());
        let first = text
            .iter()
            .flat_map(|t| t.lines())
            .map(str::trim)
            .find(|l| !l.is_empty())
            .unwrap_or("");
        return Err(format!(
            "omarchy-theme-set failed ({}): {first}",
            out.status
        ));
    }
    Ok(())
}

/// Running under Hyprland: windows are drawn without a title bar (like
/// Omarchy's own apps); elsewhere the toolkit's decorations are kept.
pub fn is_hyprland() -> bool {
    std::env::var_os("HYPRLAND_INSTANCE_SIGNATURE").is_some()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_omarchy_colors() {
        let t = parse_colors(
            "# Generated by Aether\nmode = \"light\"\n\naccent = \"#89B4FA\"\nbackground = \"#1e1e2e\"\nforeground = \"#cdd6f4\"\n",
            "wet-girl".into(),
        )
        .unwrap();
        assert_eq!(t.mode, "light");
        assert_eq!(t.colors["accent"], "#89b4fa");
        assert_eq!(t.colors.len(), 3);
    }

    #[test]
    fn only_hex_colors_reach_css() {
        let t = parse_colors(
            "background = \"#000\"\nforeground = \"#fff\"\naccent = \"red; background: url(x)\"\nBad-Key = \"#fff\"\nmode = \"evil\"\n",
            String::new(),
        )
        .unwrap();
        assert!(!t.colors.contains_key("accent"));
        assert!(!t.colors.contains_key("Bad-Key"));
        assert_eq!(t.mode, "dark");
    }

    #[test]
    fn incomplete_palettes_are_ignored() {
        assert!(parse_colors("accent = \"#89b4fa\"", String::new()).is_none());
    }
}

#[cfg(test)]
mod wallpaper_theme_tests {
    /// Visual check on real previews: RP_THEME_PREVIEWS (paths, `:`-separated)
    /// -> an HTML report with each preview and its palette at RP_THEME_REPORT.
    /// `cargo test -p rustpaper-selector theme_report -- --ignored`
    #[test]
    #[ignore]
    fn theme_report() {
        let (Some(list), Some(out)) = (
            std::env::var_os("RP_THEME_PREVIEWS"),
            std::env::var_os("RP_THEME_REPORT"),
        ) else {
            return;
        };
        let mut html = String::from(
            "<html><body style='margin:0;font:12px sans-serif;background:#111;color:#eee'>",
        );
        for path in std::env::split_paths(&list) {
            let Ok(p) = super::image_palette(&path) else {
                continue;
            };
            let bg = p.get("background").unwrap().hex();
            let fg = p.get("foreground").unwrap().hex();
            html += &format!(
                "<div style='display:flex;gap:8px;padding:6px;background:{bg};color:{fg}'><img src='file://{}' style='height:90px'><div><b>{} {}</b><div style='display:flex;flex-wrap:wrap;width:620px'>",
                path.display(),
                if p.dark { "dark" } else { "light" },
                p.icon_theme()
            );
            for (k, c) in &p.entries {
                html += &format!(
                    "<div style='width:46px;margin:1px'><div style='height:22px;background:{}'></div><div style='font-size:8px'>{k}</div></div>",
                    c.hex()
                );
            }
            html += "</div></div></div>";
        }
        std::fs::write(out, html + "</body></html>").unwrap();
    }
}

