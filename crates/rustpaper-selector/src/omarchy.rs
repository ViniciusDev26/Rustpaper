// Desktop integration with Omarchy (Hyprland): the selector follows the
// active Omarchy theme's colors, and switches with it.
//
// Omarchy publishes the current theme in
// $XDG_STATE_HOME/omarchy/current/theme/colors.toml: a flat semantic palette
// (`background`, `foreground`, `accent`, `red`, ...) plus `mode` (dark /
// light). `current/theme.generation` changes on every theme switch, so a
// cheap poll of that one file is enough to notice it.

use std::collections::BTreeMap;
use std::path::PathBuf;
use std::time::Duration;

use serde::Serialize;
use tauri::Emitter;

/// How often the theme generation file is checked.
const POLL: Duration = Duration::from_secs(2);

#[derive(Serialize, Clone, Debug, PartialEq)]
pub struct Theme {
    pub name: String,
    /// "dark" | "light"
    pub mode: String,
    /// semantic name -> "#rrggbb" (only hex colors are kept)
    pub colors: BTreeMap<String, String>,
}

fn current_dir() -> Option<PathBuf> {
    let state = std::env::var_os("XDG_STATE_HOME")
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("HOME").map(|h| PathBuf::from(h).join(".local/state")))?;
    Some(state.join("omarchy").join("current"))
}

/// The active Omarchy theme, None outside Omarchy.
pub fn theme() -> Option<Theme> {
    let dir = current_dir()?;
    let text = std::fs::read_to_string(dir.join("theme").join("colors.toml")).ok()?;
    let name = std::fs::read_to_string(dir.join("theme.name"))
        .map(|n| n.trim().to_string())
        .unwrap_or_default();
    parse_colors(&text, name)
}

/// `key = "value"` lines of colors.toml (Omarchy writes nothing else: no
/// tables, no arrays). Values must be hex colors, except `mode`; the result
/// ends up in CSS custom properties, so anything else is dropped.
fn parse_colors(text: &str, name: String) -> Option<Theme> {
    let mut colors = BTreeMap::new();
    let mut mode = String::from("dark");
    for line in text.lines() {
        let line = line.trim();
        if line.starts_with('#') || line.is_empty() {
            continue;
        }
        let Some((key, value)) = line.split_once('=') else {
            continue;
        };
        let key = key.trim();
        let value = value.trim().trim_matches('"');
        if key == "mode" {
            if value == "light" || value == "dark" {
                mode = value.to_string();
            }
        } else if is_key(key) && is_hex_color(value) {
            colors.insert(key.to_string(), value.to_ascii_lowercase());
        }
    }
    // a palette without the basics is not a theme we can apply
    (colors.contains_key("background") && colors.contains_key("foreground")).then_some(Theme {
        name,
        mode,
        colors,
    })
}

fn is_key(k: &str) -> bool {
    !k.is_empty()
        && k.bytes()
            .all(|b| b.is_ascii_lowercase() || b == b'_' || b.is_ascii_digit())
}

fn is_hex_color(v: &str) -> bool {
    let Some(hex) = v.strip_prefix('#') else {
        return false;
    };
    matches!(hex.len(), 3 | 6 | 8) && hex.bytes().all(|b| b.is_ascii_hexdigit())
}

/// Emits `theme-changed` (the new Theme, or null) whenever Omarchy switches
/// themes. A no-op loop outside Omarchy costs one failed stat every POLL.
pub fn watch(app: tauri::AppHandle) {
    std::thread::spawn(move || {
        let generation =
            || current_dir().and_then(|d| std::fs::read_to_string(d.join("theme.generation")).ok());
        let mut last = generation();
        loop {
            std::thread::sleep(POLL);
            let now = generation();
            if now != last {
                last = now;
                let _ = app.emit("theme-changed", theme());
            }
        }
    });
}

/// Running under Hyprland: windows are drawn without a title bar (like
/// Omarchy's own apps); elsewhere the toolkit's decorations are kept.
pub fn is_hyprland() -> bool {
    std::env::var_os("HYPRLAND_INSTANCE_SIGNATURE").is_some()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_omarchy_colors() {
        let t = parse_colors(
            "# Generated by Aether\nmode = \"light\"\n\naccent = \"#89B4FA\"\nbackground = \"#1e1e2e\"\nforeground = \"#cdd6f4\"\n",
            "wet-girl".into(),
        )
        .unwrap();
        assert_eq!(t.mode, "light");
        assert_eq!(t.colors["accent"], "#89b4fa");
        assert_eq!(t.colors.len(), 3);
    }

    #[test]
    fn only_hex_colors_reach_css() {
        let t = parse_colors(
            "background = \"#000\"\nforeground = \"#fff\"\naccent = \"red; background: url(x)\"\nBad-Key = \"#fff\"\nmode = \"evil\"\n",
            String::new(),
        )
        .unwrap();
        assert!(!t.colors.contains_key("accent"));
        assert!(!t.colors.contains_key("Bad-Key"));
        assert_eq!(t.mode, "dark");
    }

    #[test]
    fn incomplete_palettes_are_ignored() {
        assert!(parse_colors("accent = \"#89b4fa\"", String::new()).is_none());
    }
}
