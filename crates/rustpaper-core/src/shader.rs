// `shader` module: translates the Wallpaper Engine shader "dialect" into GLSL 330
// that naga (wgpu's GLSL frontend) can compile.
//
// WE shaders (`.vert`/`.frag` in the base assets) are NOT plain GLSL: they are a
// cross-compile dialect (HLSL+GLSL) with:
//   - `#include "common_*.h"`  — custom includes (resolved from shaders/)
//   - HLSL-style macros: `mul()`, `frac`, `saturate`, `lerp`, `CAST3`, `texSample2D`...
//   - legacy GLSL: `attribute`, `varying`, `gl_FragColor`
//   - `#if COMBO` — feature flags ("combos") set per material
//
// The strategy (same as linux-wallpaperengine, see ShaderUnit.cpp) is to build a
// PRELUDE of `#define`s that maps the dialect to GLSL 330 and prepend it to the code
// with the includes resolved and the combos defined. The result is GLSL that
// naga's preprocessor+frontend understands. Here we only produce the GLSL TEXT; the
// engine compiles it for the GPU (via `wgpu::ShaderSource::Glsl`).

use std::collections::HashSet;
use std::path::Path;

/// Pipeline stage — changes which compatibility `#define`s are included and how
/// `varying` is translated (output in the vertex stage, input in the fragment stage).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Stage {
    Vertex,
    Fragment,
}

// Prelude common to all stages: maps the WE dialect (HLSL-ish) to GLSL.
// Copied 1:1 from linux-wallpaperengine's SHADER_HEADER (ground truth) — each
// line resolves a construct that naga would not swallow raw.
// #version 450 (not 330 like lwe): we need explicit `layout(binding=)` on the
// separate samplers, which only exists from 420 on.
const PRELUDE: &str = "#version 450\n\
    precision highp float;\n\
    #define mul(x, y) ((y) * (x))\n\
    #define max(x, y) max(y, x)\n\
    #define lerp mix\n\
    #define frac fract\n\
    #define CAST2(x) (vec2(x))\n\
    #define CAST3(x) (vec3(x))\n\
    #define CAST4(x) (vec4(x))\n\
    #define CAST3X3(x) (mat3(x))\n\
    #define float2 vec2\n\
    #define float3 vec3\n\
    #define float4 vec4\n\
    #define int2 ivec2\n\
    #define int3 ivec3\n\
    #define int4 ivec4\n\
    #define saturate(x) (clamp(x, 0.0, 1.0))\n\
    #define texSample2D(tex, coord) texture(sampler2D(tex, _smp_##tex), coord)\n\
    #define texSample2DLod(tex, coord, lod) textureLod(sampler2D(tex, _smp_##tex), coord, lod)\n\
    #define log10(x) (log2(x) * 0.301029995663981)\n\
    #define atan2 atan\n\
    #define fmod(x, y) ((x)-(y)*trunc((x)/(y)))\n\
    #define ddx dFdx\n\
    #define ddy(x) dFdy(-(x))\n\
    #define GLSL 1\n";

// In the fragment stage, `varying` is an INPUT and there is an explicit color output.
const FRAGMENT_DEFINES: &str = "out vec4 out_FragColor;\n#define varying in\n";
// In the vertex stage, `attribute` is an input and `varying` is an OUTPUT.
const VERTEX_DEFINES: &str = "#define attribute in\n#define varying out\n";

/// Translates a WE shader to GLSL 330.
///
/// - `stage`: vertex or fragment.
/// - `source`: raw contents of the `.vert`/`.frag`.
/// - `combos`: (NAME, value) pairs of the material's feature flags. They become
///   `#define NAME value` (name in uppercase, as WE expects in `#if`s).
/// - `shaders_dir`: folder of the base shaders (e.g. `we-assets/shaders`) used to
///   resolve the `#include`s.
pub fn translate(
    stage: Stage,
    source: &str,
    combos: &[(String, i64)],
    shaders_dir: &Path,
) -> Result<String, String> {
    // 1) resolve includes recursively (naga has no #include).
    let mut seen = HashSet::new();
    let with_includes = resolve_includes(source, shaders_dir, &mut seen)?;

    // 1b) resolve `#require` (modules generated by WE, e.g. LightingV1).
    let with_includes = resolve_requires(&with_includes);

    // 2) gl_FragColor -> out_FragColor (destination declared in the fragment prelude).
    let body = with_includes.replace("gl_FragColor", "out_FragColor");

    // 3) split combined samplers (`sampler2D`, GL style) into texture2D +
    // sampler (Vulkan/wgpu style). See `separate_samplers`.
    let body = separate_samplers(&body);

    // 4) assemble the result: prelude + stage defines + combos + body.
    let mut out = String::with_capacity(PRELUDE.len() + body.len() + 512);
    out.push_str(PRELUDE);
    out.push_str(match stage {
        Stage::Vertex => VERTEX_DEFINES,
        Stage::Fragment => FRAGMENT_DEFINES,
    });
    for (name, value) in combos {
        out.push_str(&format!("#define {} {}\n", name.to_uppercase(), value));
    }
    out.push('\n');
    out.push_str(&body);
    Ok(out)
}

/// OpenGL flavour of the WE dialect prelude (used by `rustpaper-gl`).
///
/// `clamp` follows HLSL: min(max(x, lo), hi), defined even when lo > hi. GLSL
/// leaves that case undefined and NVIDIA returns lo: the workshop bokeh
/// 2798319181 writes `clamp(0, 0.15, depth)`, which gave depth 0.15 for an
/// in-focus pixel and blurred the whole layer (こきん 3146507587: film grain
/// detail 1.69 -> 0.17 in its last pass; WE keeps it sharp).
///
/// Much closer to what the WE files expect than the Vulkan path: samplers stay
/// COMBINED (`sampler2D`), uniforms stay loose (no block, no bindings) and are
/// set by name at runtime. Only the HLSL-isms and legacy GLSL keywords need macros.
const GL_PRELUDE: &str = "#version 330 core\n\
    #define mul(x, y) ((y) * (x))\n\
    #define lerp mix\n\
    #define frac fract\n\
    #define CAST2(x) (vec2(x))\n\
    #define CAST3(x) (vec3(x))\n\
    #define CAST4(x) (vec4(x))\n\
    #define CAST3X3(x) (mat3(x))\n\
    #define float2 vec2\n\
    #define float3 vec3\n\
    #define float4 vec4\n\
    #define int2 ivec2\n\
    #define int3 ivec3\n\
    #define int4 ivec4\n\
    #define saturate(x) (clamp(x, 0.0, 1.0))\n\
    #define clamp(x, lo, hi) (min(max(x, lo), hi))\n\
    #define texSample2D texture\n\
    #define texSample2DLod textureLod\n\
    #define texture2D texture\n\
    #define log10(x) (log2(x) * 0.301029995663981)\n\
    #define atan2 atan\n\
    #define fmod(x, y) ((x)-(y)*trunc((x)/(y)))\n\
    #define ddx dFdx\n\
    #define ddy(x) dFdy(-(x))\n\
    #define GLSL 1\n";

/// HLSL promotes a scalar argument of max/min/pow to the vector size;
/// GLSL only has some of those overloads (e.g. no `max(float, vec3)`, no
/// `pow(vec3, float)`). Route them through overloads covering every mix. They
/// are declared before the macros, so their bodies call the GLSL built-ins.
const GL_SCALAR_PROMOTION: &str = "\
    float _rp_max(float a, float b) { return max(a, b); }\n\
    int _rp_max(int a, int b) { return max(a, b); }\n\
    vec2 _rp_max(vec2 a, vec2 b) { return max(a, b); }\n\
    vec3 _rp_max(vec3 a, vec3 b) { return max(a, b); }\n\
    vec4 _rp_max(vec4 a, vec4 b) { return max(a, b); }\n\
    vec2 _rp_max(vec2 a, float b) { return max(a, b); }\n\
    vec3 _rp_max(vec3 a, float b) { return max(a, b); }\n\
    vec4 _rp_max(vec4 a, float b) { return max(a, b); }\n\
    vec2 _rp_max(float a, vec2 b) { return max(b, a); }\n\
    vec3 _rp_max(float a, vec3 b) { return max(b, a); }\n\
    vec4 _rp_max(float a, vec4 b) { return max(b, a); }\n\
    float _rp_min(float a, float b) { return min(a, b); }\n\
    int _rp_min(int a, int b) { return min(a, b); }\n\
    vec2 _rp_min(vec2 a, vec2 b) { return min(a, b); }\n\
    vec3 _rp_min(vec3 a, vec3 b) { return min(a, b); }\n\
    vec4 _rp_min(vec4 a, vec4 b) { return min(a, b); }\n\
    vec2 _rp_min(vec2 a, float b) { return min(a, b); }\n\
    vec3 _rp_min(vec3 a, float b) { return min(a, b); }\n\
    vec4 _rp_min(vec4 a, float b) { return min(a, b); }\n\
    vec2 _rp_min(float a, vec2 b) { return min(b, a); }\n\
    vec3 _rp_min(float a, vec3 b) { return min(b, a); }\n\
    vec4 _rp_min(float a, vec4 b) { return min(b, a); }\n\
    float _rp_pow(float a, float b) { return pow(a, b); }\n\
    vec2 _rp_pow(vec2 a, vec2 b) { return pow(a, b); }\n\
    vec3 _rp_pow(vec3 a, vec3 b) { return pow(a, b); }\n\
    vec4 _rp_pow(vec4 a, vec4 b) { return pow(a, b); }\n\
    vec2 _rp_pow(vec2 a, float b) { return pow(a, vec2(b)); }\n\
    vec3 _rp_pow(vec3 a, float b) { return pow(a, vec3(b)); }\n\
    vec4 _rp_pow(vec4 a, float b) { return pow(a, vec4(b)); }\n\
    #define max(x, y) _rp_max(x, y)\n\
    #define min(x, y) _rp_min(x, y)\n\
    #define pow(x, y) _rp_pow(x, y)\n";

const GL_FRAGMENT_DEFINES: &str = "out vec4 out_FragColor;\n#define varying in\n";
const GL_VERTEX_DEFINES: &str = "#define attribute in\n#define varying out\n";

/// Translates a WE shader to GLSL 330 core for OpenGL.
///
/// Same steps as [`translate`] (includes, `#require`, combos, `gl_FragColor`),
/// but WITHOUT splitting samplers: in GL a `sampler2D` uniform is just a texture
/// unit index, which is exactly what the WE shaders were written for.
pub fn translate_gl(
    stage: Stage,
    source: &str,
    combos: &[(String, i64)],
    shaders_dir: &Path,
) -> Result<String, String> {
    let mut seen = HashSet::new();
    let body = resolve_includes(source, shaders_dir, &mut seen)?;
    let body = resolve_requires(&body);
    let body = body.replace("gl_FragColor", "out_FragColor");
    let (samplers, body) = hoist_samplers(&body);

    let mut out = String::with_capacity(GL_PRELUDE.len() + body.len() + 512);
    out.push_str(GL_PRELUDE);
    out.push_str(match stage {
        Stage::Vertex => GL_VERTEX_DEFINES,
        Stage::Fragment => GL_FRAGMENT_DEFINES,
    });
    for (name, value) in combos {
        out.push_str(&format!("#define {} {}\n", name.to_uppercase(), value));
    }
    out.push_str(GL_SCALAR_PROMOTION);
    out.push_str(&samplers);
    // `#line 1` keeps driver error line numbers close to the WE source.
    out.push_str("#line 1\n");
    out.push_str(&body);
    Ok(out)
}

/// Moves every `uniform sampler2D` declaration to the top (deduplicated).
///
/// WE's shader compiler collects uniform declarations before the code, so an
/// include may use `g_Texture0` that the main file only declares AFTER the
/// `#include` line (e.g. common_blur.h in every blur effect). Plain GLSL needs
/// the declaration first. Only samplers are hoisted: an unused sampler is
/// harmless, while moving other uniforms out of `#if` blocks could change meaning.
fn hoist_samplers(body: &str) -> (String, String) {
    let mut decls = String::new();
    let mut seen = HashSet::new();
    let mut rest = String::with_capacity(body.len());
    for line in body.lines() {
        if let Some((name, _)) = parse_sampler_decl(line) {
            if seen.insert(name.clone()) {
                decls.push_str(&format!("uniform sampler2D {name};\n"));
            }
            rest.push_str("// (hoisted) ");
        }
        rest.push_str(line);
        rest.push('\n');
    }
    (decls, rest)
}

/// HLSL tolerates a `varying` declared vec4 in one stage and vec2 in the
/// other; GLSL won't link. Promote the smaller declaration to the bigger type
/// (its uses then become vec4 -> vec2 truncations, which the fixer swizzles).
/// Returns the rewritten (vertex, fragment).
pub fn match_varyings(vertex: &str, fragment: &str) -> (String, String) {
    fn decl(l: &str) -> Option<(String, String)> {
        let mut it = l.trim().strip_prefix("varying ")?.split_whitespace();
        let ty = it.next()?.to_string();
        let name: String = it
            .next()?
            .chars()
            .take_while(|c| c.is_ascii_alphanumeric() || *c == '_')
            .collect();
        Some((name, ty))
    }
    let types = |src: &str| -> std::collections::HashMap<String, String> {
        src.lines().filter_map(decl).collect()
    };
    let (tv, tf) = (types(vertex), types(fragment));
    let promote = |src: &str,
                   mine: &std::collections::HashMap<String, String>,
                   other: &std::collections::HashMap<String, String>| {
        src.lines()
            .map(|l| match decl(l) {
                Some((name, ty)) => match other.get(&name) {
                    Some(o)
                        if *o != ty
                            && o.starts_with("vec")
                            && ty.starts_with("vec")
                            && components(o) > components(&ty)
                            && mine.contains_key(&name) =>
                    {
                        l.replacen(&format!("varying {ty} "), &format!("varying {o} "), 1)
                    }
                    _ => l.to_string(),
                },
                None => l.to_string(),
            })
            .collect::<Vec<_>>()
            .join("\n")
            + "\n"
    };
    (promote(vertex, &tv, &tf), promote(fragment, &tf, &tv))
}

/// Repairs HLSL-isms a GLSL compiler rejected, using its error log: for each
/// error line, wrap the assigned/returned expression in the target type's
/// constructor (HLSL truncates/converts implicitly: `vec2 uv = someVec4;`) or
/// turn `a % b` on floats into `fmod`. Only the lines the compiler pointed at
/// are touched. Returns None when nothing could be fixed.
///
/// Line numbers are relative to the `#line 1` marker `translate_gl` emits.
/// Understands NVIDIA (`0(12) : error C7011: implicit cast from "vec4" to
/// "vec2"`) and Mesa (`0:12(5): error: ... from `vec4' to `vec2'`) logs.
pub fn fix_glsl_from_log(source: &str, log: &str) -> Option<String> {
    let mut lines: Vec<String> = source.lines().map(String::from).collect();
    let base = lines.iter().position(|l| l.trim() == "#line 1")?;
    let mut changed = false;
    let mut done = HashSet::new();
    for err in log.lines() {
        let Some(n) = error_line(err) else { continue };
        if !done.insert(n) {
            continue; // one fix per line per round; the next compile re-reports
        }
        let idx = base + n;
        let Some(line) = lines.get(idx).cloned() else {
            continue;
        };
        let fixed = if err.contains("unmatched #endif") {
            Some(format!("// (stray #endif removed) {line}"))
        } else if err.contains("non constant expression")
            || err.contains("constant expression required")
        {
            // HLSL allows `const` locals with runtime values
            line.contains("const ")
                .then(|| line.replacen("const ", "", 1))
        } else if let Some((from, to)) = conversion_types(err) {
            let local = |name: &str| declared_type_before(&lines, idx, name);
            multi_declarator(&line, &to)
                .or_else(|| ternary_condition(&line, &to))
                .or_else(|| uint_operands(&line, &to, &local))
                .or_else(|| swizzle_operands(&line, &from, &to, &local))
                .or_else(|| wrap_rhs(&line, &to))
        } else if err.contains('%') && (err.contains("integral") || err.contains("integer")) {
            integer_or_float_modulo(&line)
        } else if err.contains("invalid operands to") {
            bool_arithmetic(&line)
        } else if err.contains("unexpected '('") {
            // a function named like one of our prelude macros (log10...)
            shadowed_macro(&line, &lines[..base]).map(|name| format!("#undef {name}\n{line}"))
        } else {
            None
        };
        if let Some(f) = fixed
            && f != line
        {
            lines[idx] = f;
            changed = true;
        }
    }
    // whole-source rewrites
    let mut text = lines.join("\n") + "\n";
    for err in log.lines() {
        if let Some(name) = quoted_after(err, "assignment to varying '") {
            if let Some(t) = varying_to_local(&text, &name) {
                text = t;
                changed = true;
            }
        } else if err.contains("reserves names containing '__'") {
            let t = rename_double_underscores(&text);
            if t != text {
                text = t;
                changed = true;
            }
        }
    }
    changed.then_some(text)
}

fn quoted_after(err: &str, prefix: &str) -> Option<String> {
    let rest = &err[err.find(prefix)? + prefix.len()..];
    Some(rest[..rest.find('\'')?].to_string())
}

/// HLSL converts bools in arithmetic: `(a < b) * 6.0` -> `float(a < b) * 6.0`.
fn bool_arithmetic(line: &str) -> Option<String> {
    let b = line.as_bytes();
    let mut i = 0;
    while let Some(k) = line[i..].find('(') {
        let open = i + k;
        let prev = line[..open].trim_end().chars().last();
        let is_call = prev.is_some_and(|c| c.is_ascii_alphanumeric() || c == '_');
        let mut depth = 0;
        let mut close = None;
        for (j, &ch) in b.iter().enumerate().skip(open) {
            match ch {
                b'(' => depth += 1,
                b')' => {
                    depth -= 1;
                    if depth == 0 {
                        close = Some(j);
                        break;
                    }
                }
                _ => {}
            }
        }
        let close = close?;
        let inner = &line[open + 1..close];
        let cmp = ["<=", ">=", "==", "!=", "<", ">"]
            .iter()
            .any(|o| inner.contains(o));
        if !is_call && cmp && !inner.contains('(') && !inner.contains('?') {
            return Some(format!("{}float{}", &line[..open], &line[open..]));
        }
        i = open + 1;
    }
    None
}

/// `float log10(float x) {` while the prelude has `#define log10(x) ...`:
/// returns the macro name so it can be #undef'd first.
fn shadowed_macro(line: &str, prelude: &[String]) -> Option<String> {
    let toks: Vec<&str> = line
        .split(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
        .filter(|t| !t.is_empty())
        .collect();
    let name = toks.get(1)?;
    let def = format!("#define {name}(");
    (GLSL_TYPES.contains(toks.first()?) && prelude.iter().any(|l| l.trim_start().starts_with(&def)))
        .then(|| name.to_string())
}

/// Fragment shaders may write to their inputs in HLSL. Rename the input and
/// copy it into a global of the original name at the start of `main`.
fn varying_to_local(src: &str, name: &str) -> Option<String> {
    let mut out = String::with_capacity(src.len() + 128);
    let mut declared = None;
    for l in src.lines() {
        let t = l.trim_start();
        let words: Vec<&str> = t.trim_end_matches(';').split_whitespace().collect();
        if declared.is_none()
            && words.len() == 3
            && (words[0] == "in" || words[0] == "varying")
            && words[2] == name
        {
            declared = Some(words[1].to_string());
            out.push_str(&format!(
                "in {} _rp_in_{name};\n{} {name};\n",
                words[1], words[1]
            ));
            continue;
        }
        out.push_str(l);
        out.push('\n');
    }
    declared?;
    let main = out.find("void main(")?;
    let brace = main + out[main..].find('{')?;
    out.insert_str(brace + 1, &format!("\n\t{name} = _rp_in_{name};"));
    Some(out)
}

/// GLSL reserves identifiers containing `__` (Workshop shaders use them).
fn rename_double_underscores(src: &str) -> String {
    let mut out = String::with_capacity(src.len());
    let mut word = String::new();
    let flush = |word: &mut String, out: &mut String| {
        if word.contains("__") && !word.starts_with("__") && !word.ends_with("__") {
            out.push_str(&word.replace("__", "_rpu_"));
        } else if word.contains("__") && word.chars().all(|c| c == '_') {
            out.push_str(&"_rpu".repeat(word.len()));
        } else {
            out.push_str(word);
        }
        word.clear();
    };
    for c in src.chars() {
        if c.is_ascii_alphanumeric() || c == '_' {
            word.push(c);
        } else {
            flush(&mut word, &mut out);
            out.push(c);
        }
    }
    flush(&mut word, &mut out);
    out
}

/// Type of `name` from its nearest declaration above line `idx` (shaders
/// reuse names with different types in different functions).
fn declared_type_before(lines: &[String], idx: usize, name: &str) -> Option<String> {
    for l in lines[..=idx.min(lines.len() - 1)].iter().rev() {
        let toks: Vec<&str> = l
            .split(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
            .filter(|t| !t.is_empty())
            .collect();
        for w in toks.windows(2) {
            if w[1] == name && GLSL_TYPES.contains(&w[0]) {
                return Some(w[0].to_string());
            }
        }
    }
    None
}

/// `vec2 a = 0.0, b = 0.0, c = x;` (HLSL broadcasts the scalar to each).
fn multi_declarator(line: &str, to: &str) -> Option<String> {
    let t = line.trim_start();
    let indent = &line[..line.len() - t.len()];
    let rest = t.strip_prefix(to)?.strip_prefix(' ')?;
    let semi = rest.rfind(';')?;
    let (body, tail) = rest.split_at(semi);
    let parts = split_top_level(body, ',');
    if parts.len() < 2 {
        return None;
    }
    let decls: Vec<String> = parts
        .iter()
        .map(|p| match p.split_once('=') {
            Some((name, expr)) => format!("{} = {to}({})", name.trim(), expr.trim()),
            None => p.trim().to_string(),
        })
        .collect();
    Some(format!("{indent}{to} {}{tail}", decls.join(", ")))
}

fn split_top_level(s: &str, sep: char) -> Vec<&str> {
    let (mut depth, mut start, mut out) = (0i32, 0, Vec::new());
    for (i, c) in s.char_indices() {
        match c {
            '(' | '[' => depth += 1,
            ')' | ']' => depth -= 1,
            c if c == sep && depth == 0 => {
                out.push(&s[start..i]);
                start = i + 1;
            }
            _ => {}
        }
    }
    out.push(&s[start..]);
    out
}

/// `X ? a : b` with an int condition (a combo) -> `bool(X) ? a : b`.
fn ternary_condition(line: &str, to: &str) -> Option<String> {
    if to != "bool" {
        return None;
    }
    let q = line.find('?')?;
    let before = line[..q].trim_end();
    let start = before
        .rfind(|c: char| !(c.is_ascii_alphanumeric() || c == '_' || c == '.'))
        .map_or(0, |k| k + 1);
    let cond = &before[start..];
    if cond.is_empty() {
        return None;
    }
    Some(format!(
        "{}bool({cond}){}",
        &line[..start],
        &line[before.len()..]
    ))
}

/// Unsigned targets (no implicit int -> uint in GLSL): `1` -> `1u`, int
/// variables and combo macros (ALL_CAPS) -> `uint(x)`.
fn uint_operands(line: &str, to: &str, ty_of: &dyn Fn(&str) -> Option<String>) -> Option<String> {
    if !to.starts_with('u') {
        return None;
    }
    let code_end = line.find("//").unwrap_or(line.len());
    let (code, comment) = line.split_at(code_end);
    let lhs_end = code.find('=').map_or(0, |e| e + 1);
    let (lhs, rhs) = code.split_at(lhs_end);
    let mut out = String::from(lhs);
    let b = rhs.as_bytes();
    let mut i = 0;
    let mut changed = false;
    while i < b.len() {
        let c = b[i] as char;
        let prev_word = i > 0
            && ((b[i - 1] as char).is_ascii_alphanumeric() || b[i - 1] == b'_' || b[i - 1] == b'.');
        if prev_word || !(c.is_ascii_alphanumeric() || c == '_') {
            out.push(c);
            i += 1;
            continue;
        }
        let start = i;
        while i < b.len() && ((b[i] as char).is_ascii_alphanumeric() || b[i] == b'_') {
            i += 1;
        }
        let tok = &rhs[start..i];
        let next = rhs[i..].chars().next();
        if tok.chars().all(|c| c.is_ascii_digit()) {
            out.push_str(tok);
            if !matches!(next, Some('.') | Some('e') | Some('E')) {
                out.push('u');
                changed = true;
            }
        } else if next != Some('(')
            && tok != "uint"
            && (ty_of(tok).as_deref() == Some("int")
                || (tok.len() > 1
                    && tok
                        .chars()
                        .all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || c == '_')))
        {
            out.push_str(&format!("uint({tok})"));
            changed = true;
        } else {
            out.push_str(tok);
        }
    }
    out.push_str(comment);
    changed.then_some(out)
}

/// "0(352) : error ..." (NVIDIA) or "0:352(12): error: ..." (Mesa) -> 352
fn error_line(err: &str) -> Option<usize> {
    let rest = err.trim_start().strip_prefix('0')?;
    let rest = rest.strip_prefix('(').or_else(|| rest.strip_prefix(':'))?;
    let digits: String = rest.chars().take_while(|c| c.is_ascii_digit()).collect();
    digits.parse().ok()
}

const GLSL_TYPES: &[&str] = &[
    "float", "int", "uint", "bool", "vec2", "vec3", "vec4", "ivec2", "ivec3", "ivec4", "uvec2",
    "uvec3", "uvec4",
];

/// (from, to) of an implicit-conversion error.
fn conversion_types(err: &str) -> Option<(String, String)> {
    if !(err.contains("implicit cast")
        || err.contains("implicit narrowing")
        || err.contains("implicit conversion")
        || err.contains("cannot convert"))
    {
        return None;
    }
    let ty_after = |s: &str| -> String {
        s.trim_start_matches(['"', '`', '\'', ' '])
            .chars()
            .take_while(|c| c.is_ascii_alphanumeric())
            .collect()
    };
    let to = ty_after(&err[err.rfind(" to ")? + 4..]);
    let from = ty_after(&err[err.find(" from ")? + 6..]);
    (GLSL_TYPES.contains(&to.as_str()) && GLSL_TYPES.contains(&from.as_str())).then_some((from, to))
}

fn components(ty: &str) -> usize {
    ty.chars()
        .last()
        .and_then(|c| c.to_digit(10))
        .map_or(1, |d| d as usize)
}

/// HLSL truncates bigger vectors used with smaller ones (`vec4 * vec2`):
/// append the swizzle to identifiers declared with the source type.
fn swizzle_operands(
    line: &str,
    from: &str,
    to: &str,
    ty_of: &dyn Fn(&str) -> Option<String>,
) -> Option<String> {
    let (nf, nt) = (components(from), components(to));
    if !from.contains("vec") || nt >= nf {
        return None;
    }
    let swz = &"xyzw"[..nt];
    let code_end = line.find("//").unwrap_or(line.len());
    let mut out = String::new();
    let mut changed = false;
    let mut i = 0;
    let b = line.as_bytes();
    let mut prev_ident = "";
    while i < line.len() {
        let c = b[i] as char;
        if i < code_end
            && (c.is_ascii_alphabetic() || c == '_')
            && (i == 0
                || !((b[i - 1] as char).is_ascii_alphanumeric()
                    || b[i - 1] == b'_'
                    || b[i - 1] == b'.'))
        {
            let start = i;
            while i < line.len() && ((b[i] as char).is_ascii_alphanumeric() || b[i] == b'_') {
                i += 1;
            }
            let ident = &line[start..i];
            out.push_str(ident);
            let next = line[i..].trim_start().chars().next();
            // `vec4 x = ...` declares x: swizzling it gave `vec4 x.xy`
            let declared = GLSL_TYPES.contains(&prev_ident);
            prev_ident = ident;
            if !declared
                && ty_of(ident).as_deref() == Some(from)
                && !matches!(next, Some('.') | Some('(') | Some('['))
            {
                out.push('.');
                out.push_str(swz);
                changed = true;
            }
            continue;
        }
        out.push(c);
        i += 1;
    }
    changed.then_some(out)
}

/// `x = expr;` / `T x = expr;` / `for (int i = expr; ...` / `return expr;`
/// -> wrap expr in `ty(...)`, once. With several statements on one line, the
/// first one not wrapped yet is fixed (the next compile reports the rest).
fn wrap_rhs(line: &str, ty: &str) -> Option<String> {
    let mut start = 0;
    while start < line.len() {
        let end = line[start..].find(';').map_or(line.len(), |k| start + k);
        if let Some(fixed) = wrap_statement(&line[start..end], ty) {
            return Some(format!("{}{fixed}{}", &line[..start], &line[end..]));
        }
        start = end + 1;
    }
    None
}

fn wrap_statement(stmt: &str, ty: &str) -> Option<String> {
    let already = |e: &str| e.starts_with(&format!("{ty}(")) && e.ends_with(')');
    if let Some(i) = stmt.find("return ") {
        let expr = stmt[i + 7..].trim();
        if expr.is_empty() || already(expr) {
            return None;
        }
        return Some(format!("{}return {ty}({expr})", &stmt[..i]));
    }
    // first '=' that is an assignment (not ==, <=, >=, !=)
    let b = stmt.as_bytes();
    let eq = (0..b.len()).find(|&k| {
        b[k] == b'=' && b.get(k + 1) != Some(&b'=') && (k == 0 || !b"=<>!".contains(&b[k - 1]))
    })?;
    let expr = stmt[eq + 1..].trim();
    if expr.is_empty() || already(expr) {
        return None;
    }
    Some(format!("{} {ty}({expr})", &stmt[..eq + 1]))
}

/// `a % b` with a float operand: in an integer declaration cast both operands
/// to that integer type, otherwise it's HLSL's fmod.
fn integer_or_float_modulo(line: &str) -> Option<String> {
    let t = line.trim_start();
    let int_ty = ["uint ", "int "]
        .iter()
        .find(|p| t.starts_with(**p))
        .map(|p| p.trim());
    let i = line.find('%')?;
    let is_operand = |c: char| c.is_ascii_alphanumeric() || "_.[]".contains(c);
    let left_start = line[..i]
        .trim_end()
        .rfind(|c: char| !is_operand(c))
        .map_or(0, |k| k + 1);
    let left = line[left_start..i].trim();
    let right_part = line[i + 1..].trim_start();
    let right_len = right_part
        .find(|c: char| !is_operand(c))
        .unwrap_or(right_part.len());
    let right = &right_part[..right_len];
    if left.is_empty() || right.is_empty() {
        return None;
    }
    let after = &right_part[right_len..];
    Some(match int_ty {
        Some(ty) => format!("{}{ty}({left}) % {ty}({right}){after}", &line[..left_start]),
        None => format!(
            "{}fmod(float({left}), float({right})){after}",
            &line[..left_start]
        ),
    })
}

/// Annotation of a `uniform sampler2D` declaration in a WE shader.
///
/// `uniform sampler2D g_Texture1; // {"combo":"MASK","default":"util/white","hidden":true}`
/// - `default`: texture to bind when neither the material nor the scene sets one;
/// - `combo`: combo that is defined to 1 when a texture IS provided for this slot
///   (this is how WE switches e.g. the mask code path on).
#[derive(Debug, Clone, PartialEq, Default)]
pub struct SamplerAnnotation {
    pub name: String,
    pub default: Option<String>,
    pub combo: Option<String>,
}

/// Parses every `uniform sampler2D` declaration (with or without annotation).
pub fn parse_samplers(source: &str) -> Vec<SamplerAnnotation> {
    let mut out = Vec::new();
    for line in source.lines() {
        let Some((name, comment)) = parse_sampler_decl(line) else {
            continue;
        };
        let json = serde_json::from_str::<serde_json::Value>(comment.trim()).ok();
        let field = |k: &str| {
            json.as_ref()
                .and_then(|j| j.get(k))
                .and_then(|v| v.as_str())
                .map(String::from)
        };
        out.push(SamplerAnnotation {
            name,
            default: field("default"),
            combo: field("combo"),
        });
    }
    out
}

// Expands `#include "file.h"` recursively, inserting the contents in place of the
// directive. Each file is included AT MOST once (dedupe by name) — works
// as an include guard, avoiding redefinitions (GLSL has no `#pragma once`).
fn resolve_includes(
    source: &str,
    shaders_dir: &Path,
    seen: &mut HashSet<String>,
) -> Result<String, String> {
    let mut out = String::with_capacity(source.len());
    for line in source.lines() {
        if let Some(name) = parse_include(line) {
            if seen.insert(name.clone()) {
                let path = shaders_dir.join(&name);
                let content = std::fs::read_to_string(&path)
                    .map_err(|e| format!("include {name:?} not found ({}): {e}", path.display()))?;
                out.push_str(&format!("// begin include {name}\n"));
                out.push_str(&resolve_includes(&content, shaders_dir, seen)?);
                out.push_str(&format!("\n// end include {name}\n"));
            }
            // already included before: omit (dedupe)
        } else {
            out.push_str(line);
            out.push('\n');
        }
    }
    Ok(out)
}

/// `source` with its `#include`s expanded (each file once); unreadable
/// includes are left out. Used to read uniform annotations that live in
/// headers (e.g. `g_CompositeColor`, default "1 1 1", in common_composite.h).
pub fn expand_includes(source: &str, shaders_dir: &Path) -> String {
    let mut out = String::with_capacity(source.len());
    let mut seen = HashSet::new();
    for line in source.lines() {
        match parse_include(line) {
            Some(name) if seen.insert(name.clone()) => {
                if let Ok(content) = std::fs::read_to_string(shaders_dir.join(&name)) {
                    // nested includes share the dedupe set
                    let nested =
                        resolve_includes(&content, shaders_dir, &mut seen).unwrap_or(content);
                    out.push_str(&nested);
                    out.push('\n');
                }
            }
            Some(_) => {}
            None => {
                out.push_str(line);
                out.push('\n');
            }
        }
    }
    out
}

// Stub of the LightingV1 module: in WE, `PerformLighting_V1` is generated dynamically
// from the scene's lights. Since (like linux-wallpaperengine) there is no support
// for light objects yet, we generate a stub that contributes no dynamic light. Without
// it, shaders that `#require LightingV1` (e.g. genericimage4) do not compile.
const LIGHTING_V1_STUB: &str = "// generated module LightingV1\n\
    vec3 PerformLighting_V1(vec3 worldPos, vec3 albedo, vec3 normal, vec3 viewDir,\n\
    vec3 specularTint, vec3 baseReflectance, float roughness, float metallic) {\n\
    return vec3(0.0);\n\
    }\n";

// Replaces `#require <module>` directives with the module's code. We only know
// LightingV1; others become a comment (with an inline warning) so parsing does not break.
fn resolve_requires(source: &str) -> String {
    let mut out = String::with_capacity(source.len());
    for line in source.lines() {
        if let Some(module) = line.trim_start().strip_prefix("#require") {
            match module.trim() {
                "LightingV1" => out.push_str(LIGHTING_V1_STUB),
                other => out.push_str(&format!("// #require {other} (unsupported module)\n")),
            }
        } else {
            out.push_str(line);
            out.push('\n');
        }
    }
    out
}

/// A material parameter declared in the shader: the uniform, the parameter name in the
/// material (`"material"` in the annotation), the default value and how many components it has.
/// E.g.: `uniform vec3 g_TintColor; // {"material":"color","default":"1 0 0"}`
/// becomes `{ uniform:"g_TintColor", material:Some("color"), default:[1,0,0], components:3 }`.
#[derive(Debug, Clone, PartialEq)]
pub struct UniformParam {
    pub uniform: String,
    pub material: Option<String>,
    pub default: Vec<f32>,
    pub components: usize,
}

// Number of components of a scalar/vector GLSL type (what fits in the UBO as floats).
fn type_components(ty: &str) -> Option<usize> {
    match ty {
        "float" | "int" => Some(1),
        "vec2" => Some(2),
        "vec3" => Some(3),
        "vec4" => Some(4),
        _ => None,
    }
}

// Reads a default from the annotation: number -> [n]; string "1 0 0" -> [1,0,0].
// Workshop shaders also write "0.0, 1.0" (commas).
fn parse_default(v: &serde_json::Value, components: usize) -> Vec<f32> {
    let mut out = match v {
        serde_json::Value::Number(n) => vec![n.as_f64().unwrap_or(0.0) as f32],
        serde_json::Value::String(s) => s
            .split(|c: char| c.is_whitespace() || c == ',')
            .filter_map(|t| t.parse::<f32>().ok())
            .collect(),
        _ => Vec::new(),
    };
    out.resize(components, 0.0);
    out
}

/// Extracts the annotated material parameters of a shader (lines
/// `uniform <type> <name>; // {json}`). Ignores samplers and uniforms without a valid
/// JSON annotation. Used to build the UBO with defaults + material overrides.
pub fn parse_params(source: &str) -> Vec<UniformParam> {
    let mut out = Vec::new();
    for line in source.lines() {
        let t = line.trim();
        let Some(rest) = t.strip_prefix("uniform ") else {
            continue;
        };
        let Some((decl, comment)) = rest.split_once("//") else {
            continue;
        };
        // decl = "<type> <name> ;" (with ; at the end)
        let decl = decl.trim().trim_end_matches(';').trim();
        let mut it = decl.split_whitespace();
        let (Some(ty), Some(name)) = (it.next(), it.next()) else {
            continue;
        };
        // name may have [N] (array) — we ignore arrays for now
        if name.contains('[') {
            continue;
        }
        let Some(components) = type_components(ty) else {
            continue;
        };
        let Ok(json) = serde_json::from_str::<serde_json::Value>(comment.trim()) else {
            continue;
        };
        let material = json
            .get("material")
            .and_then(|m| m.as_str())
            .map(String::from);
        let default = json
            .get("default")
            .map(|d| parse_default(d, components))
            .unwrap_or_else(|| vec![0.0; components]);
        out.push(UniformParam {
            uniform: name.to_string(),
            material,
            default,
            components,
        });
    }
    out
}

/// Defaults of the combos declared via `// [COMBO] {"combo":"NAME","default":N}` in the
/// shader. WE uses these defaults when the material/scene does not override the combo.
/// Without this, shaders with `#if BLENDMODE` etc. do not compile (undefined identifier).
pub fn parse_combo_defaults(source: &str) -> Vec<(String, i64)> {
    let mut out = Vec::new();
    for line in source.lines() {
        let t = line.trim_start();
        let Some(rest) = t.strip_prefix("// [COMBO]") else {
            continue;
        };
        let Ok(json) = serde_json::from_str::<serde_json::Value>(rest.trim()) else {
            continue;
        };
        let (Some(name), Some(def)) = (
            json.get("combo").and_then(|c| c.as_str()),
            json.get("default").and_then(|d| d.as_i64()),
        ) else {
            continue;
        };
        out.push((name.to_string(), def));
    }
    out
}

/// Default texture of each annotated sampler: `uniform sampler2D g_Texture1;
/// // {"default":"util/noise"}` -> ("g_Texture1", "util/noise"). Used to know which
/// texture to load into a slot the material does not fill (e.g. filmgrain's noise).
pub fn parse_sampler_defaults(source: &str) -> Vec<(String, String)> {
    let mut out = Vec::new();
    for line in source.lines() {
        let Some((name, comment)) = parse_sampler_decl(line) else {
            continue;
        };
        if let Ok(json) = serde_json::from_str::<serde_json::Value>(comment.trim())
            && let Some(def) = json.get("default").and_then(|d| d.as_str())
        {
            out.push((name, def.to_string()));
        }
    }
    out
}

/// Binding of the free-uniforms block (WeGlobals) in descriptor set 0.
pub const UNIFORM_BLOCK_BINDING: u32 = 0;

/// Bindings of a `g_TextureN` texture: the image and its accompanying sampler.
/// We reserve binding 0 for the uniforms block, so N=0 → (1, 2), N=1 → (3, 4)...
/// Deterministic (derived from the index, not the order) so vertex and fragment match.
pub fn texture_bindings(index: u32) -> (u32, u32) {
    (2 * index + 1, 2 * index + 2)
}

// Rewrites `uniform sampler2D g_TextureN;` declarations (COMBINED samplers,
// OpenGL style) into two separate declarations in Vulkan/wgpu style:
//   layout(binding = t) uniform texture2D g_TextureN;
//   layout(binding = s) uniform sampler   _smp_g_TextureN;
// The texSample2D/Lod macros in the prelude reassemble `sampler2D(tex, _smp_tex)` at
// sampling time. This is necessary because wgpu (WebGPU) uses texture and sampler as
// distinct bindings — there is no combined sampler as in GL.
fn separate_samplers(source: &str) -> String {
    let mut out = String::with_capacity(source.len());
    for line in source.lines() {
        if let Some((name, comment)) = parse_sampler_decl(line) {
            let (tb, sb) = match name.strip_prefix("g_Texture").and_then(|s| {
                let digits: String = s.chars().take_while(|c| c.is_ascii_digit()).collect();
                digits.parse::<u32>().ok()
            }) {
                Some(idx) => texture_bindings(idx),
                // Sampler without the g_TextureN pattern: put it in high bindings so it does not
                // collide with the numbered textures' bindings or the block.
                None => (900, 901),
            };
            out.push_str(&format!(
                "layout(binding = {tb}) uniform texture2D {name}; // {comment}\n\
                 layout(binding = {sb}) uniform sampler _smp_{name};\n"
            ));
        } else {
            out.push_str(line);
            out.push('\n');
        }
    }
    out
}

// Recognizes `uniform sampler2D NAME;` (with variable spacing and an optional comment).
// Returns (name, comment_without_slashes). None if the line is not that.
fn parse_sampler_decl(line: &str) -> Option<(String, String)> {
    let t = line.trim();
    let rest = t.strip_prefix("uniform")?;
    let rest = rest.trim_start().strip_prefix("sampler2D")?;
    // needs a space after the type (otherwise "sampler2DArray" would match)
    if !rest.starts_with(char::is_whitespace) {
        return None;
    }
    let rest = rest.trim_start();
    let semi = rest.find(';')?;
    let name = rest[..semi].trim();
    if name.is_empty() || !name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') {
        return None;
    }
    let comment = rest[semi + 1..]
        .trim()
        .trim_start_matches('/')
        .trim()
        .to_string();
    Some((name.to_string(), comment))
}

// Extracts the name from an `#include "x.h"` (ignoring whitespace). Returns None if the
// line is not an include.
fn parse_include(line: &str) -> Option<String> {
    let t = line.trim_start();
    let rest = t.strip_prefix("#include")?;
    let start = rest.find('"')? + 1;
    let end = rest[start..].find('"')? + start;
    Some(rest[start..end].to_string())
}

